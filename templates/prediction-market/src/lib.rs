//! A binary (YES/NO) prediction market with parimutuel payouts.
//!
//! Stakers back one of two outcomes with a SEP-41 token; a single designated
//! oracle reports which one happened; winners then split the whole pool in
//! proportion to what they staked:
//!
//! * **One pool** — YES and NO stakes are escrowed together by the contract.
//!   A winner is entitled to `stake * total_pool / winning_pool`, so the
//!   losing side's stakes are what pays the winning side's profit.
//! * **Betting close** — the market has a close time (a ledger timestamp)
//!   fixed at deploy time. `stake` only works before it and `resolve` only
//!   works from it on, so nobody can still buy in once the outcome can be
//!   reported. The close instant itself counts as closed.
//! * **Oracle** — `resolve` is gated on one address fixed at deploy time.
//!   Nobody else can report an outcome, and it can only be reported once.
//! * **Pull payments** — nothing is pushed on resolution. Each winner claims
//!   their own payout, exactly once.
//! * **Rounding** — payouts are floor-divided, so up to `winning_pool - 1`
//!   units can stay behind in the contract as dust.
//!
//! Two edges this template deliberately leaves open, both worth closing
//! before using it for real:
//!
//! * There is no deadline for the oracle — if it never calls `resolve` (a lost
//!   key, an abandoned market), the stakes stay in the contract and there is no
//!   refund path.
//! * If the oracle resolves to a side nobody staked, there are no winners and
//!   the pool stays in the contract; every `claim` reports `NothingToClaim`.
//!
//! Generated by [soroban-forge](https://github.com/soroban-forge-labs/soroban-forge).

#![no_std]

use soroban_sdk::{
    contract, contracterror, contractimpl, contracttype, panic_with_error, symbol_short, token,
    Address, Env,
};

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq)]
#[repr(u32)]
pub enum Error {
    /// Stake amount was zero or negative.
    InvalidAmount = 1,
    /// The market has already been resolved.
    AlreadyResolved = 2,
    /// The market has not been resolved yet.
    NotResolved = 3,
    /// Caller is not the designated oracle.
    NotOracle = 4,
    /// This address has already taken its payout.
    AlreadyClaimed = 5,
    /// Nothing is owed to this address.
    NothingToClaim = 6,
    /// The close time given to the constructor is not in the future.
    CloseTimeInPast = 7,
    /// The betting close time has been reached: staking is closed.
    BettingClosed = 8,
    /// The betting close time has not been reached yet: resolving is not open.
    BettingStillOpen = 9,
}

#[contracttype]
#[derive(Clone)]
pub enum DataKey {
    /// The only address allowed to resolve the market.
    Oracle,
    /// SEP-41 token stakes are denominated in.
    Token,
    /// Ledger timestamp from which staking is closed and resolving is open.
    CloseTime,
    /// The winning outcome. Its *presence* is what marks the market resolved.
    Outcome,
    /// Total staked on one outcome.
    Pool(bool),
    /// One address's stake on one outcome.
    Stake(Address, bool),
    /// Whether an address has taken its payout.
    Claimed(Address),
}

fn oracle(env: &Env) -> Address {
    env.storage().instance().get(&DataKey::Oracle).unwrap()
}

fn token_address(env: &Env) -> Address {
    env.storage().instance().get(&DataKey::Token).unwrap()
}

fn close_time(env: &Env) -> u64 {
    env.storage().instance().get(&DataKey::CloseTime).unwrap()
}

/// Whether betting has closed. The close instant itself counts as closed, so
/// "before the close" (staking) and "from the close on" (resolving) are exact
/// complements.
fn betting_closed(env: &Env) -> bool {
    env.ledger().timestamp() >= close_time(env)
}

/// The winning outcome, or `None` while the market is still open.
fn resolved_outcome(env: &Env) -> Option<bool> {
    env.storage().instance().get(&DataKey::Outcome)
}

fn pool(env: &Env, outcome: bool) -> i128 {
    env.storage()
        .instance()
        .get(&DataKey::Pool(outcome))
        .unwrap_or(0)
}

fn total_pool(env: &Env) -> i128 {
    pool(env, true) + pool(env, false)
}

fn stake_of(env: &Env, who: &Address, outcome: bool) -> i128 {
    env.storage()
        .persistent()
        .get(&DataKey::Stake(who.clone(), outcome))
        .unwrap_or(0)
}

fn claimed(env: &Env, who: &Address) -> bool {
    env.storage()
        .persistent()
        .get(&DataKey::Claimed(who.clone()))
        .unwrap_or(false)
}

#[contract]
pub struct PredictionMarketContract;

#[contractimpl]
impl PredictionMarketContract {
    /// Deploy-time setup.
    ///
    /// * `oracle` — the only address that will be able to `resolve`
    /// * `token` — address of the token stakes are made in
    /// * `close_time` — unix timestamp (seconds) from which staking is closed
    ///   and the oracle may resolve. Must be in the future.
    pub fn __constructor(env: Env, oracle: Address, token: Address, close_time: u64) {
        if close_time <= env.ledger().timestamp() {
            panic_with_error!(&env, Error::CloseTimeInPast);
        }
        env.storage().instance().set(&DataKey::Oracle, &oracle);
        env.storage().instance().set(&DataKey::Token, &token);
        env.storage()
            .instance()
            .set(&DataKey::CloseTime, &close_time);
    }

    /// Stake `amount` on an outcome — `true` for YES, `false` for NO.
    ///
    /// The tokens are transferred into the contract's escrow. Staking is only
    /// possible before the close time; an address may stake more than once,
    /// and may stake on both sides.
    pub fn stake(env: Env, from: Address, outcome: bool, amount: i128) {
        from.require_auth();
        if amount <= 0 {
            panic_with_error!(&env, Error::InvalidAmount);
        }
        if resolved_outcome(&env).is_some() {
            panic_with_error!(&env, Error::AlreadyResolved);
        }
        if betting_closed(&env) {
            panic_with_error!(&env, Error::BettingClosed);
        }

        token::Client::new(&env, &token_address(&env)).transfer(
            &from,
            &env.current_contract_address(),
            &amount,
        );

        let new_stake = stake_of(&env, &from, outcome) + amount;
        env.storage()
            .persistent()
            .set(&DataKey::Stake(from.clone(), outcome), &new_stake);
        env.storage()
            .instance()
            .set(&DataKey::Pool(outcome), &(pool(&env, outcome) + amount));

        env.events()
            .publish((symbol_short!("stake"), from, outcome), amount);
    }

    /// Report the winning outcome. Only the oracle may call this, only once,
    /// and only once betting has closed — so nobody can still stake when the
    /// outcome becomes reportable.
    ///
    /// `caller` is passed explicitly rather than authorizing the stored
    /// oracle directly, so the address that signed is checked against the
    /// designated one — a wrong signer is rejected, not silently accepted.
    pub fn resolve(env: Env, caller: Address, outcome: bool) {
        caller.require_auth();
        if caller != oracle(&env) {
            panic_with_error!(&env, Error::NotOracle);
        }
        if resolved_outcome(&env).is_some() {
            panic_with_error!(&env, Error::AlreadyResolved);
        }
        if !betting_closed(&env) {
            panic_with_error!(&env, Error::BettingStillOpen);
        }
        env.storage().instance().set(&DataKey::Outcome, &outcome);

        env.events()
            .publish((symbol_short!("resolve"), caller), outcome);
    }

    /// Pay out `to`'s share of the pool and return the amount transferred.
    ///
    /// Anyone may trigger a claim on a winner's behalf — the funds always go
    /// to `to`, so there is nothing to gain by doing so. Each address can
    /// claim exactly once.
    pub fn claim(env: Env, to: Address) -> i128 {
        if resolved_outcome(&env).is_none() {
            panic_with_error!(&env, Error::NotResolved);
        }
        if claimed(&env, &to) {
            panic_with_error!(&env, Error::AlreadyClaimed);
        }

        let winner = resolved_outcome(&env).unwrap();
        let staked = stake_of(&env, &to, winner);
        if staked == 0 {
            panic_with_error!(&env, Error::NothingToClaim);
        }

        // `staked > 0` implies `winning_pool >= staked > 0`, so the division
        // is always safe. Flooring leaves at most `winning_pool - 1` units of
        // dust in the contract.
        let payout = staked * total_pool(&env) / pool(&env, winner);

        env.storage()
            .persistent()
            .set(&DataKey::Claimed(to.clone()), &true);

        token::Client::new(&env, &token_address(&env)).transfer(
            &env.current_contract_address(),
            &to,
            &payout,
        );

        env.events().publish((symbol_short!("claim"), to), payout);
        payout
    }

    // --- read-only getters ---

    pub fn get_oracle(env: Env) -> Address {
        oracle(&env)
    }

    pub fn get_token(env: Env) -> Address {
        token_address(&env)
    }

    /// The ledger timestamp from which staking is closed and resolving is open.
    pub fn get_close_time(env: Env) -> u64 {
        close_time(&env)
    }

    /// The winning outcome, or `None` while the market is unresolved.
    pub fn get_outcome(env: Env) -> Option<bool> {
        resolved_outcome(&env)
    }

    /// Total staked on one side.
    pub fn get_pool(env: Env, outcome: bool) -> i128 {
        pool(&env, outcome)
    }

    /// Everything escrowed by the market, both sides together.
    pub fn get_total_pool(env: Env) -> i128 {
        total_pool(&env)
    }

    /// What `who` staked on one side.
    pub fn get_stake(env: Env, who: Address, outcome: bool) -> i128 {
        stake_of(&env, &who, outcome)
    }

    /// Whether `who` has already taken their payout.
    pub fn has_claimed(env: Env, who: Address) -> bool {
        claimed(&env, &who)
    }
}

